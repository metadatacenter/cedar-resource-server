  @POST
  @Timed
  @Path("/load-valuesets-ontology")
  @Operation(summary = "Load the OWL value sets ontology generated by the caDSR CDE injestor.", description = "Load the OWL value sets ontology generated by the NCI caDSR CDE injestor. Each time the ingestor "
          + "runs (typically nightly) and new value sets ontology is created, which descibed the value sets used "
          + "by caDSR CDEs." + QUEUED_DESCRIPTION)
  @ApiResponses({
      @ApiResponse(responseCode = "202", description = "The import was queued",
          headers = @Header(name = "Location", description = "Where to poll this import.",
              schema = @Schema(type = "string"))),
      @ApiResponse(responseCode = "400", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "Bad request"),
      @ApiResponse(responseCode = "401", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "Unauthorized"),
      @ApiResponse(responseCode = "403", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "Forbidden"),
      @ApiResponse(responseCode = "404", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "Not found"),
      @ApiResponse(responseCode = "409", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "An import is already running",
          headers = @Header(name = "Location", description = "Where to poll the running import.",
              schema = @Schema(type = "string"))),
      @ApiResponse(responseCode = "500", content = @Content(schema = @Schema(implementation = CedarError.class)), description = "Internal server error")
  })
  public Response loadValueSetsOntology() throws CedarException {
    CedarRequestContext c = buildRequestContext();
    AdminCommand.LOAD_VALUESETS_ONTOLOGY.enforce(c);

    Optional<JobClaim> claim = ValueSetsImportStatusManager.getInstance().tryStart();
    if (claim.isEmpty()) {
      return importAlreadyRunning();
    }

    submitValueSetsImportJob(claim.get(), () -> {
      LoadValueSetsOntologyTask task = new LoadValueSetsOntologyTask(cedarConfig);
      CedarRequestContext cedarAdminRequestContext = CedarRequestContextFactory.fromAdminUser(cedarConfig, userService);
      task.loadValueSetsOntology(cedarAdminRequestContext);
    });

    return importQueued(claim.get());
  }

